"""
make_ablation_table.py
======================
从训练时写的 val_log CSV 聚合出消融表(论文 Table: Ablation, CP-GRU vs Full CPGD)。
对应 paper.tex 的 tab:ablation —— 三行(Raw WLS / CP-GRU Only / Full CPGD)×
五列(All / Early / Mid / Late / Blackout)的验证 RMSE。

数据源:train_prior_denoiser_v8.py 训练时每 VAL_INTERVAL 记的 val_log.csv,列:
  obs_*  = Raw WLS 观测        (obs_all/early/mid/late)
  pr_*   = CP-GRU prior 输出   (pr_all/early/mid/late, blackout_pr)
  den_*  = Full CPGD 去噪输出  (den_all/early/mid/late, blackout_den)
表值 = 收敛段(默认末 --window 步)各列的均值,与论文口径一致。

用法:
  # 取训练收敛段(默认末段)聚合消融表
  python make_ablation_table.py --val_log ./models_prior_denoiser_v8_ft/val_log.csv \
      --step_lo 12000 --step_hi 15000 --out ./mc_results/最终/table_ablation.tex
"""

import os
import csv
import argparse
import numpy as np


# 表列 -> (prior 列名, denoised 列名, obs 列名或 None)
SEGMENTS = [
    ('All',      'pr_all',   'den_all',   'obs_all'),
    ('Early',    'pr_early', 'den_early', 'obs_early'),
    ('Mid',      'pr_mid',   'den_mid',   'obs_mid'),
    ('Late',     'pr_late',  'den_late',  'obs_late'),
    ('Blackout', 'blackout_pr', 'blackout_den', None),  # 盲区无 Raw WLS
]


def load_rows(path, step_lo, step_hi):
    rows = []
    with open(path, newline='') as f:
        for r in csv.DictReader(f):
            try:
                s = float(r['step'])
            except (KeyError, ValueError):
                continue
            if step_lo <= s <= step_hi:
                rows.append(r)
    return rows


def col_mean(rows, key):
    vals = []
    for r in rows:
        v = r.get(key, '')
        if v == '' or v is None:
            continue
        try:
            fv = float(v)
        except ValueError:
            continue
        if np.isfinite(fv):
            vals.append(fv)
    return float(np.mean(vals)) if vals else float('nan')


def fmt(x):
    return '---' if not np.isfinite(x) else f'{x:.1f}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--val_log', type=str,
                    default='./models_prior_denoiser_v8_ft/val_log.csv')
    ap.add_argument('--step_lo', type=float, default=12000)
    ap.add_argument('--step_hi', type=float, default=15000)
    ap.add_argument('--out', type=str,
                    default='./mc_results/最终/table_ablation.tex')
    ap.add_argument('--tag', type=str, default='v8 fine-tuned',
                    help='caption 里注明训练口径')
    args = ap.parse_args()

    if not os.path.exists(args.val_log):
        raise SystemExit(f"[error] val_log 不存在: {args.val_log}")
    rows = load_rows(args.val_log, args.step_lo, args.step_hi)
    if not rows:
        raise SystemExit(f"[error] {args.step_lo}-{args.step_hi} 步区间无数据行")
    print(f"聚合 {len(rows)} 个验证点 (step {args.step_lo:.0f}-{args.step_hi:.0f})")

    # 三行数据
    obs_row = {seg: col_mean(rows, oc) if oc else float('nan')
               for seg, _, _, oc in SEGMENTS}
    pr_row = {seg: col_mean(rows, pc) for seg, pc, _, _ in SEGMENTS}
    den_row = {seg: col_mean(rows, dc) for seg, _, dc, _ in SEGMENTS}

    # 控制台预览
    hdr = f"  {'Config':<14}" + ''.join(f"{s:>11}" for s, *_ in SEGMENTS)
    print(hdr)
    for name, row in [('Raw WLS Obs.', obs_row), ('CP-GRU Only', pr_row),
                      ('Full CPGD', den_row)]:
        print(f"  {name:<14}" + ''.join(f"{fmt(row[s]):>11}" for s, *_ in SEGMENTS))

    # LaTeX
    lines = []
    lines.append('% Auto-generated by make_ablation_table.py')
    lines.append('\\begin{table}[htbp]\\centering')
    lines.append(f'\\caption{{Ablation: Validation RMSE at Convergence '
                 f'({args.step_lo:.0f}--{args.step_hi:.0f} Steps, {args.tag})}}')
    lines.append('\\label{tab:ablation}')
    lines.append('\\setlength{\\tabcolsep}{4pt}')
    lines.append('\\begin{tabular}{lccccc}')
    lines.append('\\toprule')
    lines.append('Configuration & All (m) & Early (m) & Mid (m) & Late (m) & Blackout (m) \\\\')
    lines.append('\\midrule')
    lines.append('Raw WLS Obs.         & ' +
                 ' & '.join(fmt(obs_row[s]) for s, *_ in SEGMENTS) + ' \\\\')
    lines.append('CP-GRU Only          & ' +
                 ' & '.join(fmt(pr_row[s]) for s, *_ in SEGMENTS) + ' \\\\')
    lines.append('\\textbf{Full CPGD}   & ' +
                 ' & '.join(fmt(den_row[s]) for s, *_ in SEGMENTS) + ' \\\\')
    lines.append('\\bottomrule')
    lines.append('\\end{tabular}')
    lines.append('\\end{table}')

    os.makedirs(os.path.dirname(args.out) or '.', exist_ok=True)
    with open(args.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f"\n[Saved] LaTeX 消融表 -> {args.out}")


if __name__ == '__main__':
    main()
